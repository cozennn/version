import { z } from 'zod';
import { ORDER_FULFILLMENT_STATUSES, ORDER_PAYMENT_STATUSES, PAYMENT_METHODS, SUPPORTED_CURRENCIES } from '../constants.js';
import { emailSchema, idSchema, orderReferenceSchema, paginationQuerySchema } from './common.js';
export const cartAddSchema = z.object({productId:idSchema,planId:idSchema,quantity:z.number().int().min(1).max(10).default(1)});
export type CartAdd = z.infer<typeof cartAddSchema>;
export const cartUpdateSchema = z.object({quantity:z.number().int().min(1).max(10)});
export type CartUpdate = z.infer<typeof cartUpdateSchema>;
export const cartLineIdSchema = z.object({lineId:idSchema});
export const checkoutSchema = z.object({email:emailSchema,customerName:z.string().trim().min(2).max(120),paymentMethod:z.enum(PAYMENT_METHODS),notes:z.string().trim().max(2000).optional()});
export type CheckoutInput = z.infer<typeof checkoutSchema>;
export const lookupOrderSchema = z.object({reference:orderReferenceSchema,email:emailSchema});
export type LookupOrderInput = z.infer<typeof lookupOrderSchema>;
export const orderQuerySchema = paginationQuerySchema.extend({status:z.enum(ORDER_PAYMENT_STATUSES).optional(),fulfillment:z.enum(ORDER_FULFILLMENT_STATUSES).optional(),q:z.string().trim().max(200).optional(),paymentMethod:z.enum(PAYMENT_METHODS).optional(),currency:z.enum(SUPPORTED_CURRENCIES).optional()});
export type OrderQuery = z.infer<typeof orderQuerySchema>;
export const demoPaypalConfirmSchema = z.object({reference:orderReferenceSchema});
export type DemoPaypalConfirmInput = z.infer<typeof demoPaypalConfirmSchema>;
export const baridimobProofUploadSchema = z.object({reference:orderReferenceSchema,email:emailSchema,note:z.string().trim().max(1000).optional()});
export type BaridimobProofUploadInput = z.infer<typeof baridimobProofUploadSchema>;
export const baridimobReviewSchema = z.object({decision:z.enum(['approve','reject']),note:z.string().trim().max(1000).optional()});
export type BaridimobReviewInput = z.infer<typeof baridimobReviewSchema>;
